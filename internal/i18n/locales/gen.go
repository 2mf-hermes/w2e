func main() {
	out := "."
	if len(os.Args) > 1 {
		out = os.Args[1]
	}
	for _, code := range []string{"en", "zh-TW", "zh-CN", "ja", "ko"} {
		m := locales[code]
		data, err := json.MarshalIndent(m, "", "  ")
		if err != nil {
			panic(err)
		}
		// ensure BOM-free UTF-8
		path := filepath.Join(out, code+".json")
		if err := os.WriteFile(path, data, 0o644); err != nil {
			panic(err)
		}
		fmt.Printf("wrote %s (%d keys, %d bytes)\n", path, len(m), len(data))
		if !strings.HasSuffix(string(data), "\n") {
			_ = os.WriteFile(path, append(data, '\n'), 0o644)
		}
	}
}
